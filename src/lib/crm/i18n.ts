/**
 * Translate a key using the current language bundle.
 * Falls back to English, then returns the key itself if missing.
 */
export function t(key: string, lang: Language = "en"): string {
  const bundle = BUNDLES[lang] ?? BUNDLES.en;
  const value = bundle[key] ?? BUNDLES.en[key] ?? key;
  return value;
}

/** Detect the browser language and map to a supported language. */
export function detectLanguage(): Language {
  const navLang = (typeof navigator !== "undefined" ? navigator.language : "en").toLowerCase();
  if (navLang.startsWith("hi")) return "hi";
  if (navLang.startsWith("es")) return "es";
  if (navLang.startsWith("fr")) return "fr";
  if (navLang.startsWith("ar")) return "ar";
  return "en";
}
