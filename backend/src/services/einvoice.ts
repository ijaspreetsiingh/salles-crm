/**
 * GST e-Invoicing (IRP/GSP) — IRN generation and QR code embedding.
 *
 * India's Invoice Registration Portal mandates that any registered taxpayer
 * above ₹5 crore aggregate turnover must generate an IRN (Invoice Reference
 * Number) for every B2B invoice and embed the signed QR code on the printed
 * copy. Without an IRN the invoice is not legally valid for input credit.
 *
 * This service wraps the IRP sandbox/production API. When no GSP credentials
 * are configured it returns a "not_configured" status so the UI can warn the
 * user instead of silently skipping compliance.
 *
 * Environment variables required (set in .env):
 *   GSP_USERNAME       — your GSP account username
 *   GSP_PASSWORD       — your GSP account password
 *   GSP_CLIENT_ID      — GSP client_id issued at onboarding
 *   GSP_CLIENT_SECRET  — GSP client_secret
 *   GSTIN              — your organisation's GSTIN (15-char alphanumeric)
 *   IRP_SANDBOX        — "true" to hit the sandbox, omit/false for production
 *
 * The IRN is 64 hex characters generated by HMAC-SHA256 over a canonical
 * payload. We store it in the record's `extra` JSON alongside the signed QR
 * blob so the PDF service can embed them without a second API call.
 */
import crypto from "node:crypto";
import { env } from "../config/env";

const SANDBOX_URL = "https://einv-apisandbox.nic.in";
/** The live IRP. This used to point at `einvoice1-apisandbox.nic.in`, which is a
 * sandbox host: with `IRP_SANDBOX` unset, a live invoice would have been sent
 * to a test portal and come back with an IRN that is not legally valid. */
const PROD_URL = "https://einvoice1.gst.gov.in";

type EInvoiceLineItem = {
  slNo: string;
  prdDesc: string;
  isServc: "Y" | "N";
  hsnCd: string;
  qty: number;
  unit: string;
  unitPrice: number;
  totAmt: number;
  assAmt: number;
  gstRt: number;
  igstAmt: number;
  cgstAmt: number;
  sgstAmt: number;
  totItemVal: number;
};

export type EInvoicePayload = {
  invoiceNumber: string;
  invoiceDate: string; // "DD/MM/YYYY"
  invoiceType: "B2B" | "B2C" | "EXPWP" | "EXPWOP";
  supplyType: "O" | "I"; // O=outward, I=inward
  buyerGstin: string;
  buyerName: string;
  buyerAddr: string;
  buyerState: string; // 2-digit state code e.g. "07"
  buyerPincode: string;
  items: EInvoiceLineItem[];
  totalAssessableValue: number;
  totalIgst: number;
  totalCgst: number;
  totalSgst: number;
  totalInvoiceValue: number;
};

export type IRNResult =
  | { status: "not_configured"; reason: string }
  | { status: "error"; reason: string; code?: string }
  | {
      status: "success";
      irn: string;
      ackNo: string;
      ackDate: string;
      signedQrCode: string;
      signedInvoice: string;
    };

/**
 * Returns true only when the integration can actually complete a call.
 *
 * `IRP_SANDBOX` must be set explicitly: "true" for the NIC sandbox, "false" for
 * the live portal. Guessing here is how an agency ends up printing a sandbox IRN
 * on a real tax invoice, so an unset value counts as "not configured".
 *
 * The session key is negotiated per auth call: the IRP returns `Sek` encrypted
 * with the 32-character AppKey we sent, and every payload is encrypted with
 * that decrypted Sek. A fixed test key is no longer accepted — the portal
 * would not be able to decrypt the payload, and a fake success is worse than a
 * clear "not configured".
 */
export function isEInvoiceConfigured(): boolean {
  const sandbox = process.env.IRP_SANDBOX;
  return Boolean(
    process.env.GSP_USERNAME &&
      process.env.GSP_PASSWORD &&
      process.env.GSP_CLIENT_ID &&
      process.env.GSP_CLIENT_SECRET &&
      process.env.GSTIN &&
      (sandbox === "true" || sandbox === "false"),
  );
}

/**
 * Generates an IRN and obtains the signed QR code from the IRP.
 *
 * The IRP authentication flow:
 *   1. POST /auth → get auth_token (valid 6 hrs)
 *   2. POST /eivital/dec/v1.03/einvoice → pass encrypted payload → get IRN + QR
 *
 * Encryption uses AES-256-ECB with the GSP's EK (encryption key), which is
 * obtained once per auth session. We keep this self-contained to avoid a
 * dependency on a GSP SDK that may differ by provider.
 */
export async function generateIRN(payload: EInvoicePayload): Promise<IRNResult> {
  if (!isEInvoiceConfigured()) {
    return {
      status: "not_configured",
      reason:
        "E-invoicing is not configured. Set GSP_USERNAME, GSP_PASSWORD, GSP_CLIENT_ID, GSP_CLIENT_SECRET, GSTIN and IRP_SANDBOX (\"true\" or \"false\"). Generate invoices without an IRN until then — do not guess these values, because an IRN from the wrong portal is not valid.",
    };
  }

  const baseUrl = process.env.IRP_SANDBOX === "true" ? SANDBOX_URL : PROD_URL;
  const gstin = process.env.GSTIN!;

  /*
   * A fresh 32-character AppKey for this auth session. The IRP encrypts the
   * returned Sek with it; it is never reused and never logged.
   */
  const appKey = crypto.randomBytes(24).toString("base64");

  try {
    // Step 1 — authenticate with the GSP and get the auth token + encryption key.
    const authRes = await fetch(`${baseUrl}/eivital/v1.03/auth`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        client_id: process.env.GSP_CLIENT_ID!,
        client_secret: process.env.GSP_CLIENT_SECRET!,
        gstin,
      },
      body: JSON.stringify({
        UserName: process.env.GSP_USERNAME,
        Password: process.env.GSP_PASSWORD,
        AppKey: appKey, // 32 chars: NIC encrypts the returned Sek with this
        ForceRefreshAccessToken: false,
      }),
    });

    const authJson = (await authRes.json()) as {
      Status: number;
      AuthToken?: string;
      Sek?: string; // session encryption key (base64, AES-256 encrypted with AppKey)
      error?: string;
    };

    if (authJson.Status !== 1 || !authJson.AuthToken) {
      return { status: "error", reason: authJson.error ?? "IRP authentication failed" };
    }

    const authToken = authJson.AuthToken;

    let sek: string;
    try {
      sek = decryptSek(authJson.Sek ?? "", appKey);
    } catch (error) {
      return {
        status: "error",
        reason: `IRP auth did not return a usable session key: ${(error as Error).message}`,
      };
    }

    // Step 2 — build the invoice JSON in the NIC schema and encrypt it with
    // the per-session Sek, exactly as the portal will decrypt it.
    const invoiceData = buildNicPayload(payload, gstin);
    const encryptedData = encryptWithSek(JSON.stringify(invoiceData), sek);

    // Step 3 — submit to the IRP.
    const irnRes = await fetch(`${baseUrl}/eivital/dec/v1.03/einvoice`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        client_id: process.env.GSP_CLIENT_ID!,
        client_secret: process.env.GSP_CLIENT_SECRET!,
        gstin,
        "auth-token": authToken,
      },
      body: JSON.stringify({ Data: encryptedData }),
    });

    const irnJson = (await irnRes.json()) as {
      Status: number;
      Data?: {
        Irn: string;
        AckNo: string;
        AckDt: string;
        SignedQRCode: string;
        SignedInvoice: string;
      };
      ErrorDetails?: Array<{ ErrorCode: string; ErrorMessage: string }>;
    };

    if (irnJson.Status !== 1 || !irnJson.Data) {
      const firstError = irnJson.ErrorDetails?.[0];
      return {
        status: "error",
        reason: firstError?.ErrorMessage ?? "IRP rejected the invoice",
        code: firstError?.ErrorCode,
      };
    }

    return {
      status: "success",
      irn: irnJson.Data.Irn,
      ackNo: String(irnJson.Data.AckNo),
      ackDate: irnJson.Data.AckDt,
      signedQrCode: irnJson.Data.SignedQRCode,
      signedInvoice: irnJson.Data.SignedInvoice,
    };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return { status: "error", reason: `Network error reaching IRP: ${message}` };
  }
}

/** Builds the NIC-compliant invoice JSON object from our internal payload type. */
function buildNicPayload(p: EInvoicePayload, supplierGstin: string) {
  return {
    Version: "1.1",
    TranDtls: {
      TaxSch: "GST",
      SupTyp: p.supplyType === "O" ? "B2B" : "IMPOS",
      IgstOnIntra: "N",
    },
    DocDtls: {
      Typ: p.invoiceType,
      No: p.invoiceNumber,
      Dt: p.invoiceDate,
    },
    SellerDtls: {
      Gstin: supplierGstin,
      TrdNm: process.env.ORG_LEGAL_NAME ?? "Travel Agency",
      Addr1: process.env.ORG_ADDRESS ?? "India",
      Loc: process.env.ORG_CITY ?? "Delhi",
      Pin: parseInt(process.env.ORG_PINCODE ?? "110001", 10),
      Stcd: process.env.ORG_STATE_CODE ?? "07",
    },
    BuyerDtls: {
      Gstin: p.buyerGstin,
      TrdNm: p.buyerName,
      Addr1: p.buyerAddr,
      Loc: p.buyerAddr,
      Pin: parseInt(p.buyerPincode, 10) || 110001,
      Stcd: p.buyerState,
      Pos: p.buyerState,
    },
    ItemList: p.items.map((item) => ({
      SlNo: item.slNo,
      PrdDesc: item.prdDesc,
      IsServc: item.isServc,
      HsnCd: item.hsnCd,
      Qty: item.qty,
      Unit: item.unit,
      UnitPrice: item.unitPrice,
      TotAmt: item.totAmt,
      AssAmt: item.assAmt,
      GstRt: item.gstRt,
      IgstAmt: item.igstAmt,
      CgstAmt: item.cgstAmt,
      SgstAmt: item.sgstAmt,
      TotItemVal: item.totItemVal,
    })),
    ValDtls: {
      AssVal: p.totalAssessableValue,
      IgstVal: p.totalIgst,
      CgstVal: p.totalCgst,
      SgstVal: p.totalSgst,
      TotInvVal: p.totalInvoiceValue,
    },
  };
}

/**
 * Decrypts the IRP's session encryption key.
 *
 * NIC encrypts the 32-character Sek with the AppKey using AES-256-ECB and
 * base64-encodes the result. Getting this wrong is silent: the auth call still
 * returns a token, but every payload is encrypted with the wrong key and the
 * portal rejects it. We therefore refuse anything that does not decrypt to
 * exactly 32 characters.
 */
export function decryptSek(encryptedSek: string, appKey: string): string {
  if (appKey.length !== 32) throw new Error("AppKey must be exactly 32 characters");
  if (!encryptedSek) throw new Error("auth response did not include Sek");
  const decipher = crypto.createDecipheriv("aes-256-ecb", Buffer.from(appKey, "utf8"), null);
  decipher.setAutoPadding(true);
  const plain = Buffer.concat([
    decipher.update(Buffer.from(encryptedSek, "base64")),
    decipher.final(),
  ]).toString("utf8");
  if (plain.length !== 32) throw new Error("decrypted Sek is not 32 characters");
  return plain;
}

/**
 * AES-256-ECB encryption for IRP payloads with the session key.
 *
 * ECB is the IRP's requirement — it is not a choice we would make elsewhere,
 * but the portal only accepts this exact scheme.
 */
export function encryptWithSek(plaintext: string, sek: string): string {
  if (sek.length !== 32) throw new Error("Sek must be exactly 32 characters");
  const cipher = crypto.createCipheriv("aes-256-ecb", Buffer.from(sek, "utf8"), null);
  cipher.setAutoPadding(true);
  return Buffer.concat([cipher.update(plaintext, "utf8"), cipher.final()]).toString("base64");
}

/**
 * Builds the QR code data URL from the SignedQRCode JWT returned by the IRP.
 * Uses the `qrcode` package (already in package.json) to generate a PNG data URL.
 */
export async function irnToQrDataUrl(signedQrCode: string): Promise<string> {
  try {
    const QRCode = await import("qrcode");
    return await QRCode.toDataURL(signedQrCode, { errorCorrectionLevel: "M", width: 200 });
  } catch {
    return "";
  }
}
